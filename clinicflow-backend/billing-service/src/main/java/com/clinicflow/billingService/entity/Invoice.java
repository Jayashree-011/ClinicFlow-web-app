package com.clinicflow.billingService.entity;
import lombok.*;
import jakarta.persistence.*;
import java.math.BigDecimal;
import java.time.LocalDateTime;
@Entity
@Table(name = "invoices")
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class Invoice {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long invoiceId;

    @Column(nullable = false)
    private Long patientId;

    @Column(nullable = true)
    private String patientName;   // denormalised from consultation-service at creation time

    @Column
    private Long encounterId;

    /** Set when this invoice was auto-generated from an appointment booking. */
    @Column
    private Long appointmentId;

    /** Set when this invoice was auto-generated from a prescription being issued. */
    @Column
    private Long prescriptionId;

    /** Set when this invoice was auto-generated from a lab order. */
    @Column
    private Long labOrderId;

    /** Human-readable summary auto-generated by BillingService on create/update. */
    @Column(length = 500)
    private String description;

    @Column(columnDefinition = "TEXT")
    private String lineItemsJson;
     // e.g., "PAID", "PENDING", "CANCELLED"
    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal subtotal;
    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal taxes;
    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal discounts;
    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal totalAmount;
    @Enumerated(EnumType.STRING)
    @Column(nullable = false)   
    private InvoiceStatus status;
    @Column(nullable = false)
    private LocalDateTime issuedAt;

    public enum InvoiceStatus {
        PAID,
        PENDING,
        CANCELLED
    }
}