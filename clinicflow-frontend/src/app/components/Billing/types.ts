export type InvoiceStatus = 'PAID' | 'PENDING' | 'CANCELLED';

// PaymentMethod matches Payment.PaymentMethod enum in backend
export type PaymentMethod = 'CASH' | 'CREDIT_CARD' | 'DEBIT_CARD' | 'INSURANCE' | 'MOBILE_PAYMENT' | 'OTHER';
export type PaymentStatus = 'COMPLETED' | 'PENDING' | 'FAILED' | 'REFUNDED';

// Matches Invoice entity fields returned by GET /invoices
export interface Invoice {
  invoiceId: number;
  patientId: number;
  patientName?: string;   // null on invoices created before this column was added
  encounterId: number;
  appointmentId?: number;
  prescriptionId?: number;
  labOrderId?: number;
  description?: string;   // auto-generated by BillingService on create/update
  subtotal: number;       // entity field name
  taxes: number;
  discounts: number;
  totalAmount: number;    // calculated by backend
  status: InvoiceStatus;
  issuedAt: string;
  lineItemsJson?: string;
}

// Matches PaymentDTO fields
export interface Payment {
  paymentId: number;
  invoiceId: number;
  patientId: number;
  amount: number;
  paymentMethod: PaymentMethod;
  paidAt: string;
  status: PaymentStatus;
}
